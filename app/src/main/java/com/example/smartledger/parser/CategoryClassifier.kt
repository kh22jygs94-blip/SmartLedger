    private val rules: List<Pair<String, List<String>>> = listOf(
        "餐饮" to listOf(
            "餐", "饭", "食", "咖啡", "奶茶", "星巴克", "瑞幸", "麦当劳", "肯德基",
            "汉堡", "外卖", "饿了么", "火锅", "烧烤", "面馆", "食堂", "甜品", "烘焙"
        ),
        "交通" to listOf(
            "滴滴", "出行", "打车", "地铁", "公交", "加油", "中国石化", "中国石油",
            "停车", "高速", "12306", "铁路", "机票", "航空", "单车", "哈啰", "充电桩"
        ),
        "购物" to listOf(
            "淘宝", "天猫", "京东", "拼多多", "唯品会", "商城", "超市", "百货",
            "旗舰店", "优衣库", "山姆", "盒马", "便利店", "服饰"
        ),
        "日用" to listOf("日用", "纸巾", "洗护", "清洁", "家居", "五金", "日化"),
        "娱乐" to listOf(
            "电影", "影城", "游戏", "腾讯视频", "爱奇艺", "优酷", "哔哩哔哩",
