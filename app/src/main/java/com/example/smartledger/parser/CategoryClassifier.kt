        ),
        "医疗" to listOf("医院", "药房", "药店", "诊所", "体检", "挂号", "医疗", "口腔"),
        "住房" to listOf("房租", "物业", "水费", "电费", "燃气", "宽带", "租金", "中介", "家政"),
        "通讯" to listOf("话费", "流量", "中国移动", "中国联通", "中国电信", "充值"),
        "学习" to listOf("课程", "培训", "书店", "图书", "教育", "考试", "网课", "学习", "文具")
    )

    fun suggest(text: String): String =
        rules.firstOrNull { (_, words) -> words.any { text.contains(it) } }?.first ?: "其他"
}
